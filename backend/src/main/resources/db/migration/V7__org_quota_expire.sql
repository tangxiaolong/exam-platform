-- ============================================================================
-- V7__org_quota_expire：机构额度有效期
--
-- 背景：V5 的额度池是「累计充值 - 累计消耗」，没有时间维度。现实中机构采购的额度
-- 基本都带期限（一个学期、一个财年），过期不清理会出现两种坏结果：
--   1) 去年买的额度今年还能用，采购对账永远对不上；
--   2) 运营手工把余额清零，又会把「已发出去的权益」和「账面余额」搞成两本账。
--
-- 设计取舍：
--   1) 有效期放在账户级（一行一个有效期），不引入「充值批次」：
--      批次表会让余额计算变成多表求和，而审计日志（ORG_QUOTA_RECHARGE）已经记录了每笔充值，
--      真要按批次对账可以从审计回溯；
--   2) NULL 表示长期有效，而不是「立即过期」——存量数据（V5 之后充值的、没写期限的）必须继续可用，
--      否则这次升级会让已有机构当场发不出权益；
--   3) 过期判断写在扣减 SQL 的条件里，而不是先查后判：只有库层拦住，
--      才不会因为并发或时钟差异在过期后仍然扣成功。
-- ============================================================================

ALTER TABLE sys_org_quota
  ADD COLUMN expire_at DATETIME NULL COMMENT '额度有效期；NULL 表示长期有效，过期后账户保留但不可再消耗';

CREATE INDEX idx_sys_org_quota_expire ON sys_org_quota (tenant_id, expire_at);
