-- ============================================================================
-- V16__paper_rule_difficulty_mix：组卷的难度配比
--
-- 现状：一条规则只能指定一个 difficulty，无法表达「简单 2 道 / 一般 5 道 / 困难 3 道」。
--
-- 设计取舍：
--   1) 配比与 difficulty 互斥：同时给会让「规则说 HARD、配比又给 EASY:2」变成未定义行为。
--      应用层直接拒绝，而不是替运营猜一个优先级；
--   2) 存 JSON 而不是拆成三列（easy_count/normal_count/hard_count）：
--      拆列等于把难度枚举钉死在表结构里，以后加「较难」这一档就要改表；
--   3) 存的是**权重**不是百分比：权重之和不要求等于 100，
--      「2/5/3」与「20/50/30」表达同一件事，运营不必先算一遍百分比；
--   4) 列可空：存量规则继续保持「单一难度」语义，行为不变。
-- ============================================================================

ALTER TABLE exam_paper_rule ADD COLUMN difficulty_mix VARCHAR(255) NULL
  COMMENT '难度配比 JSON，如 {"EASY":2,"NORMAL":5,"HARD":3}（按权重换算）；与 difficulty 互斥';
