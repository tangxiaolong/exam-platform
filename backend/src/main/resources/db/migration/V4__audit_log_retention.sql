-- ============================================================================
-- V4__audit_log_retention：审计日志的查询索引与保留期
--
-- 背景：`sys_audit_log` 只增不减。管理端每个写操作都落一条，一个活跃租户一年
-- 轻松到几十万行。V1 只有 (tenant_id, created_at) 索引，够支撑「按时间翻」，
-- 但支撑不了新加的查询面——运营最常问的是「某个动作最近谁做过」，
-- 也就是 action 等值 + 时间范围，这类查询在只有 created_at 索引时会先扫时间窗
-- 再逐行比对 action，窗口一拉大就退化成全表扫。
--
-- 设计取舍：
--   1) 索引顺序 (tenant_id, action, created_at)：租户等值 → 动作等值 → 时间范围，
--      三列都参与，且 created_at 放最后才能让范围条件变成索引的尾部扫描；
--   2) 不在本迁移里做任何数据删除：删审计是要人明确决定的事（合规、审计本身的要求），
--      由 `app.audit.archive.enabled` 控制归档任务，默认关闭；
--   3) 保留期只做「归档后物理删除」，不做逻辑删除：逻辑删除会留下占位行，
--      表照样膨胀，而审计的语义是「这条记录真实存在过」而不是「被标记为删除」。
-- ============================================================================

CREATE INDEX idx_sys_audit_log_action ON sys_audit_log (tenant_id, action, created_at);
