-- ============================================================================
-- V17__user_token_invalid_before：用户级 token 失效
--
-- 背景：角色/权限变更已经能立即生效（AuthInterceptor 每请求现查角色），
-- 账号被停用也能立即失效（V17 之前一个提交里补的 status 校验）。
-- 唯独「用户自己改了密码」没有出口——旧 token 会一直有效到过期。
--
-- 设计取舍：
--   1) 存「失效截止时间」而不是 token 黑名单：
--      黑名单要为每个签发过的 token 存一行、还要在过期后清理；而失效截止时间
--      每个用户永远只有一行，且天然随 time 前进而收敛；
--   2) 比较的是 token 的 iat（签发时间）而不是 exp：
--      iat 早于失效截止时间的一律拒绝，语义是「改密码之前签发的全部作废」；
--   3) 默认 NULL 表示从未失效过——不写默认值 NOW()，
--      否则迁移会把所有人的存量 token 一次性作废，等于强制全员重新登录；
--   4) 不加索引：只按主键 id 查单行，走的是 PRIMARY。
-- ============================================================================

ALTER TABLE sys_user ADD COLUMN token_invalid_before DATETIME NULL
  COMMENT 'token 失效截止时间：签发时间早于此值的 token 一律作废；为空表示从未强制失效';
